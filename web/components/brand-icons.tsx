// Brand marks as inline paths. Hand-drawn rather than installed:
// `lucide-react` dropped its brand set, and a package for two logos is a
// dependency `AGENTS.md` would have us ask about first.
//
// ⚠ **Two kinds live here and they colour differently.** `GithubIcon` is
// `currentColor`, because it sits in the header and the account menu and has
// to take its ink from the control around it — GitHub's own mark is
// black-or-white anyway. `SlackIcon` takes its brand's own colours through
// the `--color-vendor-*` tokens, because it names a product somebody is being
// asked to recognise and a grey Slack mark is just four grey lozenges. Those
// tokens are fixed rather than restated per theme: they read on the light
// canvas and the dark one, and a brand colour that shifts with our theme is
// no longer the brand's.

